// Makes workers/www/wrangler.staging.toml from workers/www/wrangler.toml: its own Worker name, no custom domains and no cron, so a staging deploy never takes traffic or runs the scheduled jobs.
// Usage: node tools/staging-config.mjs [name]  (default www-staging; the URL is https://<name>.jobpilotto.workers.dev). Data bindings stay as they are: staging only gets GET probes, and no secrets.
import {readFileSync, writeFileSync} from 'node:fs';
const name = process.argv[2] || 'www-staging';
let toml = readFileSync('workers/www/wrangler.toml', 'utf8');
toml = toml.replace(/^name = "www"/m, `name = "${name}"`);
toml = toml.replace(/^routes = \[[\s\S]*?^\]\n/m, '');
toml = toml.replace(/^crons = \[.*\]/m, 'crons = []');
if (/custom_domain/.test(toml) || !new RegExp(`^name = "${name}"`, 'm').test(toml) || /crons = \["/.test(toml)) throw new Error('staging config still has production routes, cron or name');
writeFileSync('workers/www/wrangler.staging.toml', `# GENERATED by tools/staging-config.mjs: a staging copy of wrangler.toml, never committed.\n${toml}`);
console.log(`staging config: ${name}`);
